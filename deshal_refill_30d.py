DAYS = 30
PER_DAY = 8
SLOT_HOURS = [0, 3, 6, 9, 12, 15, 18, 21]
START_DATE = "2026-08-10"


def _dates(n):
    import datetime as dt
    d0 = dt.date.fromisoformat(START_DATE)
    return [(d0 + dt.timedelta(days=i)).isoformat() for i in range(n)]


def build():
    q = load()
    items = q["items"]
    have = {i.get("id") for i in items}

    # Weighted round-robin pools: 3x vintage, 3x card, 1x versus(cycled), 1x headline(cycled)
    vi = ci = vsi = hi = 0
    n = 0
    dates = _dates(DAYS)
    for day_idx, date in enumerate(dates):
        for slot_idx, hour in enumerate(SLOT_HOURS):
            iid = f"deshal-refill1-{day_idx:02d}-{slot_idx}"
            if iid in have:
                continue
            when = f"{date}T{hour:02d}:00:00+00:00"
            slot_pos = slot_idx  # 0..7
            img = f"{IMG}/{day_idx:02d}_{slot_idx}.png"

            # Small pools (versus: 8, headline: 5) only run on even days, so
            # they repeat far less often across the month than a daily slot
            # would force; odd days get an extra vintage+card slot instead.
            even_day = (day_idx % 2 == 0)
            if even_day:
                kind = {0: "v", 1: "c", 2: "vs", 3: "v", 4: "c", 5: "h", 6: "v", 7: "c"}[slot_pos]
            else:
                kind = {0: "v", 1: "c", 2: "v", 3: "c", 4: "v", 5: "c", 6: "v", 7: "c"}[slot_pos]

            if kind == "v":
                setup, lines, punch, emoji, cap = VINTAGE[vi % len(VINTAGE)]
                vi += 1
                render(deshal_vintage_joke, out_path=img, setup=setup,
                       dialogue_lines=lines, punch=punch, punch_emoji=emoji)
                caption = cap + F
            elif kind == "c":
                text, theme, emoji, cap = CARD[ci % len(CARD)]
                ci += 1
                render(deshal_card, text, out_path=img, theme=theme, emoji=emoji)
                caption = cap + F
            elif kind == "vs":
                tl, tt, bl, bt, et, eb, cap = VERSUS[vsi % len(VERSUS)]
                vsi += 1
                render(deshal_versus, tl, tt, bl, bt, out_path=img,
                       emoji_top=et, emoji_bottom=eb)
                caption = cap + F
            else:  # kind == "h"
                headline, kicker, emoji, cap = HEADLINE[hi % len(HEADLINE)]
                hi += 1
                render(deshal_headline, headline, out_path=img, kicker=kicker, emoji=emoji)
                caption = cap + F

            it = {"id": iid, "account": "radio-deshal", "network": "facebook",
                  "type": "photo", "message": caption, "image_url": img,
                  "when": when, "status": "pending"}
            items.append(it)
            n += 1
        if (day_idx + 1) % 5 == 0:
            print(f"  ...{day_idx+1}/{DAYS} days built ({n} items so far)")
    save(q)
    print(f"queued {n} refill items, total {len(items)}")


if __name__ == "__main__":
    build()
