HOURS = [2, 4, 6, 9, 12, 14, 16, 18]  # 8 UTC slots


def build():
    q = load()
    items = q["items"]
    have = {i.get("id") for i in items}
    n_img = 0
    for di, day in enumerate(DAYS):
        for pi, entry in enumerate(day):
            kind = entry[0]
            ts = when(di, HOURS[pi])
            iid = f"ard-d{di+1}-{pi+1}"
            if iid in have:
                continue  # resume: already enqueued
            if kind == "text":
                items.append({"id": iid, "account": "radio-deshal", "network": "facebook",
                              "type": "text", "message": entry[1], "when": ts, "status": "pending"})
                continue
            img_path = f"{IMG}/d{di+1}_{pi+1}.png"
            if kind == "stmt":
                _, text, theme, emoji, size, caption = entry
                render(meme_statement, text, img_path, theme=theme, emoji=emoji, size=size)
            elif kind == "nobody":
                _, setup, punch, theme, emoji, caption = entry
                render(meme_nobody, setup, punch, img_path, theme=theme, emoji=emoji)
            elif kind == "split":
                # entries carry label+text pairs per panel: merge each into one block
                _, tlab, ttext, blab, btext, tt, bt, te, be, caption = entry
                render(meme_split, f"{tlab}\n{ttext}", f"{blab}\n{btext}", img_path,
                       top_theme=tt, bottom_theme=bt, top_emoji=te, bottom_emoji=be)
            n_img += 1
            print(f"  rendered {img_path}")
            items.append({"id": iid, "account": "radio-deshal", "network": "facebook",
                          "type": "photo", "message": caption, "image_url": img_path,
                          "when": ts, "status": "pending"})
    save(q)
    print(f"RADIO DESHAL: rendered {n_img} images, queue now {len(items)} items")


if __name__ == "__main__":
    build()
