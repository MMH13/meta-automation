POOLS = {"fear": FEAR, "selfdev": SELFDEV, "pain": PAIN, "transform": TRANSFORM, "resource": RESOURCE}

# Existing pending days (Aug 4-21) already have posts at 07:00 & 15:00 UTC.
# Top-up slots (new, distinct hours) for those days:
TOPUP_HOURS = [1, 4, 10, 13]
# Fresh days (Aug 22 - Sep 2) get a full 6 slots:
FULL_HOURS = [1, 4, 7, 10, 13, 15]

EXISTING_DAYS = 18   # 2026-08-04 .. 2026-08-21
FRESH_DAYS = 12      # 2026-08-22 .. 2026-09-02
START_DATE = "2026-08-04"

# Daily pool rotation, one pool key per slot position (cycles through pools
# so a single day isn't all-black or all-red)
ROTATION = ["resource", "pain", "fear", "transform", "selfdev", "hot",
            "pain", "resource", "transform", "fear"]


def _dates(n, start):
    import datetime as dt
    d0 = dt.date.fromisoformat(start)
    return [(d0 + dt.timedelta(days=i)).isoformat() for i in range(n)]


def build():
    q = load()
    items = q["items"]
    have = {i.get("id") for i in items}
    counters = {k: 0 for k in list(POOLS.keys()) + ["hot"]}
    n = 0
    seq = 0  # global slot sequence -> drives ROTATION + image numbering

    def _emit(date, hour, seq):
        nonlocal n
        iid = f"mamun-scale1-{date}-{hour:02d}"
        if iid in have:
            return
        kind = ROTATION[seq % len(ROTATION)]
        if kind == "hot":
            text = HOT[counters["hot"] % len(HOT)]
            counters["hot"] += 1
            it = {"id": iid, "account": "mamun-hossain", "network": "facebook",
                  "type": "text", "message": text,
                  "when": f"{date}T{hour:02d}:00:00+00:00", "status": "pending"}
        else:
            pool = POOLS[kind]
            theme, hook, payload = pool[counters[kind] % len(pool)]
            counters[kind] += 1
            img = f"{IMG}/{iid}.png"
            render(block_post, hook, out_path=img, theme=theme)
            it = {"id": iid, "account": "mamun-hossain", "network": "facebook",
                  "type": "photo", "message": hook.replace("*", "") + CTA,
                  "image_url": img, "when": f"{date}T{hour:02d}:00:00+00:00",
                  "status": "pending", "first_comment": "\n".join(payload)}
        items.append(it)
        n += 1
        print(f"  {iid}  ({kind})")

    dates_existing = _dates(EXISTING_DAYS, START_DATE)
    for date in dates_existing:
        for hour in TOPUP_HOURS:
            _emit(date, hour, seq)
            seq += 1

    dates_fresh = _dates(FRESH_DAYS, "2026-08-22")
    for date in dates_fresh:
        for hour in FULL_HOURS:
            _emit(date, hour, seq)
            seq += 1

    save(q)
    print(f"queued {n} new items, total {len(items)}")


if __name__ == "__main__":
    build()
